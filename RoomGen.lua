local function exitOf(model, placement)
	local exit = model:FindFirstChild("Exit")
	if not (exit and exit:IsA("BasePart")) then return nil end
	if model == startRoom() then return (placement.startExit(model, exit)) end
	return exit.CFrame
end

local function hideMarkers(room)
	for _, name in {"Enter", "Exit"} do
		local part = room:FindFirstChild(name)
		if part and part:IsA("BasePart") then part.Transparency = 1 end
	end
end

local function byName(list)
