--// "3", "wp-3", "WP_3", "waypoint 3", "Waypoint3" all count as waypoint 3, anything else (like "Part3") does not
local function waypointNumber(name)
	local lower = name:lower()
	return lower:match("^(%d+)$") or lower:match("^wp[%s%-_]*(%d+)$") or lower:match("^waypoint[%s%-_]*(%d+)$")
end

--// gives unnumbered waypoint parts a number, nearest first, the same order the game would walk them in
--// parts that already have a number are left alone, the new ones carry on after the highest
local function numberWaypoints(folder, start)
	local numbered, loose = {}, {}
	for _, node in folder:GetDescendants() do
		if not node:IsA("BasePart") then continue end
		local number = tonumber(node.Name:match("%d+"))
		if number then table.insert(numbered, {number = number, node = node}) else table.insert(loose, node) end
	end
	table.sort(numbered, function(a, b) return a.number < b.number end)
	
	local last = if #numbered > 0 then numbered[#numbered].node.Position else start
	local nextNumber = if #numbered > 0 then numbered[#numbered].number + 1 else 1
	local renamed = #loose
	while #loose > 0 do
		local best, bestDistance = 1, math.huge
		for i, node in loose do
			local distance = if last then (node.Position - last).Magnitude else 0
			if distance < bestDistance then best, bestDistance = i, distance end
		end
		local node = table.remove(loose, best)
		node.Name = tostring(nextNumber)
		nextNumber += 1
		last = node.Position
	end
	
	return renamed
end

autoAssignButton.MouseButton1Click:Connect(function()
	local selected = Selection:Get()[1]
	local model = selected and (if selected:IsA("Model") then selected else topModel(selected))
	if not model then AssignStatus.Text = "No room has been selected, please select a room in Explorer!"; return end
	
	local recording = ChangeHistoryService:TryBeginRecording("Room Gen auto organise")
	
	--// rooms organised before had an Assets folder, its folders go back into the room (merged if the room has one too)
	local oldAssets = model:FindFirstChild("Assets")
	if oldAssets then
		for _, folder in oldAssets:GetChildren() do
			local existing = model:FindFirstChild(folder.Name)
			if existing then
				for _, child in folder:GetChildren() do child.Parent = existing end
				folder:Destroy()
			else
				folder.Parent = model
			end
		end
		oldAssets:Destroy()
	end
	
	for _, name in {"PossibleDoors", "Spawners", "Lights", "Waypoints"} do folderIn(model, name) end
	
	--// RoomAsset is not used any more, rooms organised before still have an empty one
	local roomAsset = model:FindFirstChild("RoomAsset")
	if roomAsset and #roomAsset:GetChildren() == 0 then roomAsset:Destroy() end
	
	--// spawner markers (RoomGen_Table, RoomGen_Locker, RoomGen_Drawer...) left loose in the room go into Spawners
	local spawners = model.Spawners
	for _, object in model:GetChildren() do
		if object:IsA("BasePart") and object.Name:sub(1, 8) == "RoomGen_" then object.Parent = spawners end
	end
	local possibleDoors = model.PossibleDoors
	
	for _, object in model:GetChildren() do
		if object.Name == "Door" then object.Parent = possibleDoors end
	end
	
	if #possibleDoors:GetChildren() == 0 then
		warn(`[Room Gen] PossibleDoors has returned 0 (unable to find any parts named "Door")`)
	end
	
	--// waypoints left loose in the room go into the Waypoints folder, and lose their wp- bit
	local waypoints = model.Waypoints
	for _, part in model:GetDescendants() do
		if not part:IsA("BasePart") then continue end
		local number = waypointNumber(part.Name)
		if not number then continue end
		if part.Parent == model or part:IsDescendantOf(waypoints) then --// only loose in the room, a part called 1 inside a light model stays put
			part.Name = number
			part.Parent = waypoints
		end
	end
	
	--// numbering starts from a door when none of the waypoints have a number yet
	local firstDoor = possibleDoors:FindFirstChildWhichIsA("BasePart", true)
	local renamed = numberWaypoints(model.Waypoints, firstDoor and firstDoor.Position)
	
	if recording then ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit) end
	AssignStatus.Text = `Made the folders in {model.Name}, {#possibleDoors:GetChildren()} door(s) in PossibleDoors, {#spawners:GetChildren()} spawner(s){if renamed > 0 then `, numbered {renamed} waypoint(s)` else ""}`
	refresh()
end)

assignToRooms.MouseButton1Click:Connect(function()
	local selected = Selection:Get()[1]
	local model = selected and (if selected:IsA("Model") then selected else topModel(selected))
	if not model then AssignStatus.Text = "No room has been selected, please select a room in Explorer!"; return end
	
	local rooms = SS:FindFirstChild("Assets") and SS.Assets:FindFirstChild("Rooms")
	if not rooms then AssignStatus.Text = "Cannot find ServerStorage.Assets.Rooms"; return end
	if model.Parent == rooms then AssignStatus.Text = `{model.Name} is already in Assets.Rooms`; return end
	
	local clash = rooms:FindFirstChild(model.Name)
	if clash then AssignStatus.Text = `Assets.Rooms already has a room called {model.Name}, rename one of them first`; return end
	
	if not model:FindFirstChild("PossibleDoors") and wantToAssign ~= model then
		wantToAssign = model
		AssignStatus.Text = `WARNING! {model.Name} has not been through auto organise, click again within 3 seconds to place it anyway`
		task.delay(3, function()
			if wantToAssign == model then wantToAssign = nil end
		end)
		return
	end
	
	wantToAssign = nil
	local recording = ChangeHistoryService:TryBeginRecording("Room Gen place in Rooms")
	model.Parent = rooms
	if recording then ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit) end
	
	Selection:Set({model})
	AssignStatus.Text = `Placed {model.Name} inside Assets.Rooms, the generator will use it now`
end)

