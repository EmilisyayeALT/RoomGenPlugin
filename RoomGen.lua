local function loadPlacement()
	local generator = SSS:FindFirstChild("Modules") and SSS.Modules:FindFirstChild("RoomGenerator")
	local module = generator and generator:FindFirstChild("RoomGenerator") and generator.RoomGenerator:FindFirstChild("Placement")
